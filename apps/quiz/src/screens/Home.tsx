import type { TopicId } from "@ai-in-learning/shared-types";

import { APP_NAME } from "../app/appName.js";
import { TOPIC_LABELS, TOPICS } from "../app/topics.js";
import buttons from "../styles/button.module.css";
import styles from "./Home.module.css";
import screen from "./Screen.module.css";

/**
 * The home screen: what the app is, the AI notice, and one button per topic that
 * starts a session (AC-1.1, AC-1.2).
 */
export function Home({ onStart }: { readonly onStart: (topic: TopicId) => void }) {
  return (
    <section className={screen.screen} aria-labelledby="home-title">
      <h1 id="home-title" className={screen.title} tabIndex={-1}>
        {APP_NAME}
      </h1>
      <p className={screen.lead}>
        Answer 10 questions that get harder or easier with your answers, and see which concepts to
        review.
      </p>
      <p className={styles.notice}>
        <strong>Questions are generated by AI</strong> and may contain mistakes.
      </p>
      <h2 id="topics-title" className={styles.topicsTitle}>
        Choose a topic to start
      </h2>
      <ul className={styles.topics} aria-labelledby="topics-title">
        {TOPICS.map((topic) => (
          <li key={topic}>
            <button
              type="button"
              className={buttons.primary}
              onClick={() => {
                onStart(topic);
              }}
            >
              {TOPIC_LABELS[topic]}
            </button>
          </li>
        ))}
      </ul>
    </section>
  );
}
