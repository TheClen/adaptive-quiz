import { type ApiError, ErrorCode } from "@ai-in-learning/shared-types";
import { act, render, screen, within } from "@testing-library/react";
import { userEvent } from "@testing-library/user-event";
import { describe, expect, it, vi } from "vitest";

import { type ApiClient, ApiClientError, createFetchApiClient } from "../api/client.js";
import { expectNoAxeViolations } from "../testing/axe.js";
import { createFakeApiClient } from "../testing/fakeApiClient.js";
import { createFakeRunner } from "../testing/fakeRunner.js";
import {
  firstQuestion,
  lastQuestion,
  secondQuestion,
  sessionWithNineAnswers,
  sessionWithThreeAnswers,
} from "../testing/fixtures.js";
import { ApiClientProvider } from "./ApiClientContext.js";
import { errorContent } from "./errorMessages.js";
import { type InitialQuizState, QuizApp } from "./QuizApp.js";
import { RunnerProvider } from "./RunnerContext.js";

function renderQuiz(
  options: { readonly client?: ApiClient; readonly initialState?: InitialQuizState } = {},
) {
  const fake = createFakeApiClient();
  const fakeRunner = createFakeRunner();
  const client = options.client ?? fake.client;
  const user = userEvent.setup();
  const { container } = render(
    <ApiClientProvider client={client}>
      <RunnerProvider runner={fakeRunner.runner}>
        <QuizApp {...(options.initialState ? { initialState: options.initialState } : {})} />
      </RunnerProvider>
    </ApiClientProvider>,
  );
  return { fake, fakeRunner, user, container };
}

/** A fetch client whose every request gets `response`. */
function fetchClientReturning(response: () => Response): ApiClient {
  return createFetchApiClient({
    fetch: vi.fn<typeof fetch>().mockImplementation(() => Promise.resolve(response())),
  });
}

function sessionHeader() {
  return within(screen.getByRole("banner"));
}

/** Topic, "Question n of 10" and "Level n/5" are in the session header (AC-1.3). */
function expectProgress(topic: string, position: number, level: number) {
  const header = sessionHeader();
  expect(header.getByText(topic)).toBeDefined();
  expect(header.getByText(`Question ${String(position)} of 10`)).toBeDefined();
  expect(header.getByText(`Level ${String(level)}/5`)).toBeDefined();
}

describe("QuizApp home screen", () => {
  it("shows the description, the AI notice and both topics (AC-1.1)", async () => {
    const { container } = renderQuiz();

    expect(screen.getByRole("heading", { level: 1, name: "Adaptive Quiz" })).toBeDefined();
    expect(screen.getByText(/questions that get harder or easier with your answers/)).toBeDefined();
    expect(screen.getByText("Questions are generated by AI").parentElement?.textContent).toBe(
      "Questions are generated by AI and may contain mistakes.",
    );
    expect(screen.getByRole("button", { name: "JavaScript" })).toBeDefined();
    expect(screen.getByRole("button", { name: "React" })).toBeDefined();
    expect(screen.queryByRole("banner")).toBeNull();
    await expectNoAxeViolations(container);
  });
});

describe("QuizApp session start", () => {
  it("shows the loading indicator in the render right after the click (AC-1.2, NFR-1)", async () => {
    const { fake, user, container } = renderQuiz();

    await user.click(screen.getByRole("button", { name: "React" }));

    // The request is still pending: nothing has been resolved yet.
    expect(screen.getByRole("status").textContent).toBe("Preparing your question…");
    expectProgress("React", 1, 3);
    expect(fake.nextQuestionCalls).toHaveLength(1);
    await expectNoAxeViolations(container);
  });

  it("requests the first question of a new session on the chosen topic", async () => {
    const { fake, user } = renderQuiz();

    await user.click(screen.getByRole("button", { name: "JavaScript" }));

    const state = fake.nextQuestionCalls[0]?.request.state;
    expect(state).toMatchObject({ version: 1, topic: "javascript", answers: [] });
    expect(Number.isInteger(state?.seed)).toBe(true);
  });

  it("starts the code runner only when a session starts (plan §9.2)", async () => {
    const { fakeRunner, user } = renderQuiz();
    expect(fakeRunner.preloads()).toBe(0);

    await user.click(screen.getByRole("button", { name: "JavaScript" }));

    expect(fakeRunner.preloads()).toBe(1);
  });

  it("then shows question 1 with the session header, and focuses its heading", async () => {
    const { fake, user, container } = renderQuiz();
    await user.click(screen.getByRole("button", { name: "JavaScript" }));

    await act(async () => {
      fake.nextQuestionCalls[0]?.resolve(firstQuestion);
      await Promise.resolve();
    });

    const heading = screen.getByRole("heading", { level: 1, name: "Question 1" });
    expect(screen.getByText(firstQuestion.question.prompt)).toBeDefined();
    expect(screen.queryByRole("status")).toBeNull();
    expectProgress("JavaScript", 1, 3);
    expect(document.activeElement).toBe(heading);
    await expectNoAxeViolations(container);
  });
});

/** Starts a JavaScript session, shows question 1 and submits `answer`. */
async function answerFirstQuestion(answer: string) {
  const rendered = renderQuiz();
  const { fake, user } = rendered;
  await user.click(screen.getByRole("button", { name: "JavaScript" }));
  await act(async () => {
    fake.nextQuestionCalls[0]?.resolve(firstQuestion);
    await Promise.resolve();
  });
  await user.click(screen.getByRole("radio", { name: answer }));
  await user.click(screen.getByRole("button", { name: "Submit" }));
  return rendered;
}

async function resolveCall(fake: ReturnType<typeof createFakeApiClient>, index: number) {
  await act(async () => {
    fake.nextQuestionCalls[index]?.resolve(secondQuestion);
    await Promise.resolve();
  });
}

describe("QuizApp feedback", () => {
  it("shows the feedback of a correct answer, focused, with the level up (AC-6.1, AC-4.4)", async () => {
    const { container } = await answerFirstQuestion("2");

    const heading = screen.getByRole("heading", { level: 1, name: "Correct" });
    expect(document.activeElement).toBe(heading);
    expect(screen.getByText(firstQuestion.question.explanation)).toBeDefined();
    expect(screen.getByRole("status").textContent).toBe("↑Level up: 4/5");
    expectProgress("JavaScript", 1, 4);
    await expectNoAxeViolations(container);
  });

  it("shows the feedback of a wrong answer with the level down (AC-6.1, AC-4.4)", async () => {
    await answerFirstQuestion("undefined");

    expect(screen.getByRole("heading", { level: 1, name: "Incorrect" })).toBeDefined();
    expect(screen.getByRole("status").textContent).toBe("↓Level down: 2/5");
    expectProgress("JavaScript", 1, 2);
  });
});

describe("QuizApp prefetch", () => {
  it("requests the next question with the answer as soon as it is evaluated (plan §12)", async () => {
    const { fake } = await answerFirstQuestion("2");

    expect(fake.nextQuestionCalls).toHaveLength(2);
    const state = fake.nextQuestionCalls[1]?.request.state;
    expect(state?.seed).toBe(fake.nextQuestionCalls[0]?.request.state.seed);
    expect(state?.answers).toEqual([
      { kind: "single", conceptId: "closures", correct: true, stem: firstQuestion.question.prompt },
    ]);
  });

  it('shows the prefetched question at once on "Next question", focused (AC-6.4, NFR-3)', async () => {
    const { fake, user } = await answerFirstQuestion("2");
    await resolveCall(fake, 1);

    await user.click(screen.getByRole("button", { name: "Next question" }));

    const heading = screen.getByRole("heading", { level: 1, name: "Question 2" });
    expect(document.activeElement).toBe(heading);
    expect(screen.getByText(secondQuestion.question.prompt)).toBeDefined();
    expectProgress("JavaScript", 2, 4);
    // One request per question: the prefetch was the request for question 2.
    expect(fake.nextQuestionCalls).toHaveLength(2);
  });

  it('shows the loading state on "Next question" until the prefetch arrives (AC-6.4, NFR-1)', async () => {
    const { fake, user, container } = await answerFirstQuestion("2");

    await user.click(screen.getByRole("button", { name: "Next question" }));

    expect(screen.getByRole("status").textContent).toBe("Preparing your question…");
    expectProgress("JavaScript", 2, 4);
    await expectNoAxeViolations(container);

    await resolveCall(fake, 1);

    expect(screen.getByRole("heading", { level: 1, name: "Question 2" })).toBeDefined();
    expect(fake.nextQuestionCalls).toHaveLength(2);
  });

  it('shows a prefetch error on "Next question", and Retry resends the same state (AC-8.1)', async () => {
    const { fake, user } = await answerFirstQuestion("2");
    await act(async () => {
      fake.nextQuestionCalls[1]?.reject(new ApiClientError({ code: "ai_unavailable" }));
      await Promise.resolve();
    });

    // The failure waits: the visitor keeps reading the feedback.
    expect(screen.getByRole("heading", { level: 1, name: "Correct" })).toBeDefined();
    expect(screen.queryByRole("alert")).toBeNull();

    await user.click(screen.getByRole("button", { name: "Next question" }));

    const content = errorContent({ code: "ai_unavailable" });
    expect(screen.getByRole("heading", { level: 1, name: content.title })).toBeDefined();
    expectProgress("JavaScript", 2, 4);

    await user.click(screen.getByRole("button", { name: "Retry" }));

    expect(fake.nextQuestionCalls).toHaveLength(3);
    expect(fake.nextQuestionCalls[2]?.request).toEqual(fake.nextQuestionCalls[1]?.request);
    await resolveCall(fake, 2);
    expect(screen.getByRole("heading", { level: 1, name: "Question 2" })).toBeDefined();
  });

  it("prefetches nothing after the 10th answer (NFR-3)", async () => {
    const { fake, user } = renderQuiz({
      initialState: {
        screen: "answering",
        session: sessionWithNineAnswers,
        question: lastQuestion,
      },
    });

    await user.click(screen.getByRole("radio", { name: "2" }));
    await user.click(screen.getByRole("button", { name: "Submit" }));

    expect(screen.getByRole("heading", { level: 1, name: "Correct" })).toBeDefined();
    expectProgress("JavaScript", 10, 5);
    expect(screen.queryByRole("button", { name: "Next question" })).toBeNull();
    expect(fake.nextQuestionCalls).toHaveLength(0);
  });
});

/** Opens on the 10th question, answers it correctly and opens the summary. */
async function reachSummary() {
  const rendered = renderQuiz({
    initialState: { screen: "answering", session: sessionWithNineAnswers, question: lastQuestion },
  });
  const { user } = rendered;
  await user.click(screen.getByRole("radio", { name: "2" }));
  await user.click(screen.getByRole("button", { name: "Submit" }));
  await user.click(screen.getByRole("button", { name: "See your results" }));
  return rendered;
}

describe("QuizApp summary", () => {
  it("shows the summary after the 10th feedback, focused, with no request (AC-7.1, NFR-3)", async () => {
    const { fake, container } = await reachSummary();

    const heading = screen.getByRole("heading", { level: 1, name: "6 out of 10 correct" });
    expect(document.activeElement).toBe(heading);
    expect(screen.getByText("You finished at level 5/5.")).toBeDefined();
    expect(screen.getByRole("img", { name: /^Level: 3, 4, 3/ })).toBeDefined();
    expect(screen.getByRole("region", { name: "Concepts mastered" })).toBeDefined();
    expect(screen.getByRole("region", { name: "Concepts to review" })).toBeDefined();
    // The summary is outside the questions: no progress header.
    expect(screen.queryByRole("banner")).toBeNull();
    expect(fake.nextQuestionCalls).toHaveLength(0);
    expect(fake.codeReviewCalls).toHaveLength(0);
    await expectNoAxeViolations(container);
  });

  it("starts a fresh session on the same topic (AC-7.3)", async () => {
    const { fake, user } = await reachSummary();

    await user.click(screen.getByRole("button", { name: "JavaScript again" }));

    expect(screen.getByRole("status").textContent).toBe("Preparing your question…");
    expectProgress("JavaScript", 1, 3);
    expect(fake.nextQuestionCalls).toHaveLength(1);
    const state = fake.nextQuestionCalls[0]?.request.state;
    expect(state).toMatchObject({ version: 1, topic: "javascript", answers: [] });
    expect(Number.isInteger(state?.seed)).toBe(true);

    await act(async () => {
      fake.nextQuestionCalls[0]?.resolve(firstQuestion);
      await Promise.resolve();
    });
    expect(screen.getByRole("heading", { level: 1, name: "Question 1" })).toBeDefined();
  });

  it("starts a fresh session on the other topic (AC-7.3)", async () => {
    const { fake, user } = await reachSummary();

    await user.click(screen.getByRole("button", { name: "Switch to React" }));

    expect(screen.getByRole("status").textContent).toBe("Preparing your question…");
    expectProgress("React", 1, 3);
    expect(fake.nextQuestionCalls).toHaveLength(1);
    expect(fake.nextQuestionCalls[0]?.request.state).toMatchObject({
      version: 1,
      topic: "react",
      answers: [],
    });
  });
});

describe("QuizApp errors", () => {
  it.each(ErrorCode.options)(
    "shows the catalogue message for %s (AC-8.1 to AC-8.4)",
    async (code) => {
      const failure = code === "rate_limited" ? { code, retryAfterSeconds: 1_500 } : { code };
      const content = errorContent(failure);
      const { fake, user, container } = renderQuiz();
      await user.click(screen.getByRole("button", { name: "JavaScript" }));

      await act(async () => {
        fake.nextQuestionCalls[0]?.reject(new ApiClientError(failure));
        await Promise.resolve();
      });

      expect(screen.getByRole("heading", { level: 1, name: content.title })).toBeDefined();
      expect(screen.getByRole("alert").textContent).toBe(content.message);
      expect(screen.getByRole("button", { name: content.actionLabel })).toBeDefined();
      expectProgress("JavaScript", 1, 3);
      await expectNoAxeViolations(container);
    },
  );

  it("tells a rate-limited visitor when they can start again (AC-8.2)", async () => {
    const { fake, user } = renderQuiz();
    await user.click(screen.getByRole("button", { name: "React" }));

    await act(async () => {
      fake.nextQuestionCalls[0]?.reject(
        new ApiClientError({ code: "rate_limited", retryAfterSeconds: 1_500 }),
      );
      await Promise.resolve();
    });

    expect(screen.getByRole("alert").textContent).toBe(
      "This demo is limited to 5 quizzes per hour. You can start again in about 25 minutes.",
    );
  });

  it("retries with the same state and shows the question (AC-8.1)", async () => {
    const { fake, user } = renderQuiz();
    await user.click(screen.getByRole("button", { name: "JavaScript" }));
    await act(async () => {
      fake.nextQuestionCalls[0]?.reject(new ApiClientError({ code: "ai_unavailable" }));
      await Promise.resolve();
    });

    await user.click(screen.getByRole("button", { name: "Retry" }));

    expect(screen.getByRole("status").textContent).toBe("Preparing your question…");
    expect(fake.nextQuestionCalls).toHaveLength(2);
    expect(fake.nextQuestionCalls[1]?.request).toEqual(fake.nextQuestionCalls[0]?.request);

    await act(async () => {
      fake.nextQuestionCalls[1]?.resolve(firstQuestion);
      await Promise.resolve();
    });
    expect(screen.getByRole("heading", { level: 1, name: "Question 1" })).toBeDefined();
  });

  it("keeps the progress of the session through the error and the retry (AC-8.1)", async () => {
    const { fake, user } = renderQuiz({
      initialState: {
        screen: "error",
        session: sessionWithThreeAnswers,
        failure: { code: "generation_failed" },
        failedStep: "nextQuestion",
      },
    });
    expectProgress("JavaScript", 4, 4);

    await user.click(screen.getByRole("button", { name: "Retry" }));

    expect(fake.nextQuestionCalls).toHaveLength(1);
    expect(fake.nextQuestionCalls[0]?.request).toEqual({ state: sessionWithThreeAnswers });
    expectProgress("JavaScript", 4, 4);
  });

  it("goes back home when the session cannot continue", async () => {
    const { fake, user } = renderQuiz({
      initialState: {
        screen: "error",
        session: sessionWithThreeAnswers,
        failure: { code: "invalid_request" },
        failedStep: "nextQuestion",
      },
    });

    await user.click(screen.getByRole("button", { name: "Start a new session" }));

    expect(screen.getByRole("heading", { level: 1, name: "Adaptive Quiz" })).toBeDefined();
    expect(document.activeElement).toBe(screen.getByRole("heading", { level: 1 }));
    expect(screen.queryByRole("banner")).toBeNull();
    expect(fake.nextQuestionCalls).toHaveLength(0);
  });

  it("shows a malformed response as internal", async () => {
    const { user } = renderQuiz({
      client: fetchClientReturning(() =>
        Response.json({ ...firstQuestion, question: { kind: "single" } }),
      ),
    });

    await user.click(screen.getByRole("button", { name: "JavaScript" }));

    expect((await screen.findByRole("alert")).textContent).toBe("Something went wrong. Try again.");
    expect(screen.getByRole("button", { name: "Retry" })).toBeDefined();
  });

  it("never shows the text of an error response (AC-8.4)", async () => {
    const leak = "sk-ant-api03-secret TypeError at handler (routes/quiz.ts:42:7)";
    const body: ApiError = { error: { code: "ai_unavailable", message: leak } };
    const { user, container } = renderQuiz({
      client: fetchClientReturning(() => Response.json(body, { status: 503 })),
    });

    await user.click(screen.getByRole("button", { name: "JavaScript" }));

    expect((await screen.findByRole("alert")).textContent).toBe(
      "The AI service is not responding. Try again.",
    );
    expect(container.textContent).not.toContain("sk-ant");
    expect(container.textContent).not.toContain("routes/quiz.ts");
  });
});
